"""todo.py — учебный файл №2 для тренировки merge в Git.

Работает в паре с calculator.py: зоны конфликта пронумерованы одинаково,
поэтому при слиянии веток конфликты появятся сразу в двух файлах —
удобно тренировать разрешение нескольких конфликтов за один merge.

Запуск:  python todo.py
"""

# ============================================================================
# ЗОНА 1. НАСТРОЙКИ
# ============================================================================
SETTINGS = {
    "max_tasks": 10,        # максимум задач в списке
    "number_from": 1,       # с какого числа нумеровать задачи (1 или 0)
}

# ============================================================================
# ЗОНА 2. ПРИВЕТСТВИЕ
# ============================================================================
WELCOME = "Мой список задач:"

# Хранилище задач в памяти (файл ничего не сохраняет на диск).
tasks = []


def add_task(title):
    """Добавляет задачу в список."""
    if len(tasks) >= SETTINGS["max_tasks"]:
        raise RuntimeError("Список задач переполнен")
    # ЗОНА 3a. Добавьте проверку: пустой заголовок не принимаем.
    tasks.append({"title": title, "done": False})


def complete_task(number):
    """Отмечает задачу с указанным номером выполненной."""
    index = number - SETTINGS["number_from"]
    # ЗОНА 3b. Добавьте проверку выхода за границы списка.
    tasks[index]["done"] = True


def show_tasks():
    """Печатает список задач."""
    print(WELCOME)
    for number, task in enumerate(tasks, start=SETTINGS["number_from"]):
        mark = "[x]" if task["done"] else "[ ]"
        print(f"{mark} {number}. {task['title']}")


def main():
    add_task("сделать первый коммит")
    add_task("создать ветку")
    add_task("выполнить merge")
    complete_task(1)
    show_tasks()


if __name__ == "__main__":
    main()
