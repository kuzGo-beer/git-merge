
# ============================================================================
# ЗОНА 1. НАСТРОЙКИ
# Измените здесь значения на одной ветке и на другой — получите конфликт.
# ============================================================================
CONFIG = {
    "language": "ru",       # попробуйте "en"
    "precision": 2,         # сколько знаков после запятой оставлять
    "verbose": True,        # True — печатать "заголовок = значение"
}

# ============================================================================
# ЗОНА 2. ПРИВЕТСТВИЕ
# Самое удобное место для первого учебного конфликта.
# ============================================================================
GREETING = "Привет! Это учебный калькулятор."


# ============================================================================
# Обычные функции — их можно менять на разных ветках без конфликта,
# если правки находятся далеко друг от друга.
# ============================================================================
def add(a, b):
    """Сложение."""
    return a + b


def subtract(a, b):
    """Вычитание."""
    return a - b


def multiply(a, b):
    # ЗОНА 3a. Добавьте здесь свою проверку (например, запрет отрицательных).
    return a * b


def divide(a, b):
    # ЗОНА 3b. Решите, что делать при делении на ноль:
    # вернуть 0, выбросить исключение или вернуть None.
    if b == 0:
        raise ValueError("На ноль делить нельзя")
    return a / b


def format_number(value):
    """Округляет число по настройке precision (для целых ничего не меняет)."""
    if isinstance(value, float):
        return round(value, CONFIG["precision"])
    return value


def show(title, value):
    """Печатает результат с учётом настройки verbose."""
    if CONFIG["verbose"]:
        print(f"{title} = {format_number(value)}")
    else:
        print(format_number(value))


def main():
    print(GREETING)
    show("2 + 3", add(2, 3))
    show("10 - 4", subtract(10, 4))
    show("6 * 7", multiply(6, 7))
    show("10 / 4", divide(10, 4))


if __name__ == "__main__":
    main()
